  function norm(s) {
    return (s || '')
      .toString()
      .toLowerCase()
      .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
      .replace(/[أإآٱ]/g, 'ا')
      .replace(/ة/g, 'ه')
      .replace(/ى/g, 'ي')
      .replace(/[?؟!.,،:;؛'"`()\[\]{}<>/\\\-—_]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function linkify(text) {
    return text.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, function (m, label, url) {
      if (/^https?:/i.test(url)) {
        return '<a href="' + url + '" target="_blank" rel="noopener" class="mk-ext">' + label + '</a>';
      }
      return '<a href="' + url + '" class="mk-nav-btn" data-mk-go="1">' + label + '</a>';
    });
  }

