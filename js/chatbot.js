  function respond(text) {
    var quick = quickReply(text);
    if (quick) {
      setTimeout(function () {
        var t = document.querySelector('.mk-typing');
        if (t) t.remove();
        appendAnswer(quick, intentMeta(text), false);
        renderChips();
      }, 600);
      return;
    }
    var meta = intentMeta(text);
    var start = Date.now();
    callAI(text).then(function (aiAnswer) {
      var elapsed = Date.now() - start;
      if (aiAnswer) {
        history.push({ u: rewriteForAI(text), a: aiAnswer });
        if (history.length > 6) history.shift();
      }
      setTimeout(function () {
        var t = document.querySelector('.mk-typing');
        if (t) t.remove();
        appendAnswer(aiAnswer || replyFor(text), meta, !!aiAnswer);
        renderChips();
      }, Math.max(0, 700 - elapsed));
    });
  }

