  var FILLERS = ['يا حبيبي', 'حبيبي', 'ياخي', 'اخوي', 'لو سمحت', 'من فضلك', 'بليز', 'please'];
  function rewriteForAI(text) {
    var clean = norm(text);
    FILLERS.forEach(function (w) { clean = clean.split(w).join(' '); });
    clean = clean.replace(/\s+/g, ' ').trim();
    var meta = intentMeta(text);
    var intentLine = meta && meta.label ? 'النية المفهمومة من السؤال: ' + meta.label + '.\n' : '';
    var langLine = /[a-zA-Z]{3,}/.test(clean) ? 'The user is asking in English — please reply in English.\n' : 'المستخدم يسأل بالعربية — جاوب بالعربية.\n';
    return 'السياق: ' + contextLabel() + '.\n' + langLine + intentLine +
      'سؤال المستخدم بعد إعادة الصياغة بصيغة واضحة ومفهومة:\n' + clean;
  }

  // ذاكرة المحادثة — آخر 6 تبادلات حتى يقدر يرد على أسئلة المتابعة
  var history = [];

  function callAI(userText) {
    if (!AI.endpoint) return Promise.resolve(null);
    var messages = [{ role: 'system', content: buildSystemPrompt() }];
    history.forEach(function (h) {
      messages.push({ role: 'user', content: h.u });
      messages.push({ role: 'assistant', content: h.a });
    });
    messages.push({ role: 'user', content: rewriteForAI(userText) });
    return fetch(AI.endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: AI.model,
        temperature: AI.temperature,
        messages: messages
      })
    }).then(function (r) {
      if (!r.ok) return null;
      return r.json();
    }).then(function (d) {
      if (!d) return null;
      return d.response || d.output || d.result || null;
    }).catch(function () { return null; });
  }

