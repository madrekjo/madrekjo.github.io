  function wire() {
    var fab = document.getElementById('mkFab');
    var panel = document.getElementById('mkPanel');
    var close = document.getElementById('mkClose');
    var input = document.getElementById('mkInput');
    var sendBtn = document.getElementById('mkSend');

    function openPanel() {
      panel.classList.add('open');
      fab.classList.add('hidden');
      if (firstOpen) {
        firstOpen = false;
        showIntro();
      }
      setTimeout(function () { input.focus(); }, 150);
    }
    function closePanel() {
      panel.classList.remove('open');
      fab.classList.remove('hidden');
    }

    fab.addEventListener('click', openPanel);
    close.addEventListener('click', closePanel);
    document.addEventListener('click', function (e) {
      var go = e.target && e.target.closest ? e.target.closest('[data-mk-go]') : null;
      if (go) {
        e.preventDefault();
        window.location.href = go.getAttribute('href');
        return;
      }
      var start = e.target && e.target.closest ? e.target.closest('#mkStart') : null;
      if (start) beginChat();
    });
    sendBtn.addEventListener('click', function () {
      var v = input.value.trim();
      if (v) { send(v); input.value = ''; }
    });
    input.addEventListener('keydown', function (e) {
      if (e.key === 'Enter') {
        var v = input.value.trim();
        if (v) { send(v); input.value = ''; }
      }
    });
  }

