-- الدالة الآمنة للتحقق من تفعيل الميزة
create or replace function public.is_teacher_files_enabled()
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(
    (select teacher_files_enabled from public.teacher_files_settings where id = 1),
    false
  );
$$;

grant execute on function public.is_teacher_files_enabled() to anon, authenticated;

