-- ========= 7. RLS + صلاحيات =========
-- helper: RLS policy
do $$
declare
  tbl text;
  tbls text[] := array[
    'teacher_subjects','teacher_fields','teacher_grades',
    'teachers',
    'teacher_subject_links','teacher_field_links','teacher_grade_links',
    'teacher_sections','teacher_contents'
  ];
begin
  foreach tbl in array tbls loop
    execute format('alter table public.%I enable row level security', tbl);

    -- قراءة: مفعلة أم أدمن
    execute format(
      'create policy "%s_read" on public.%s for select to anon, authenticated
       using (public.is_teacher_files_enabled() OR public.has_role(auth.uid(), ''admin''))',
      tbl, tbl
    );

    -- كتابة/تعديل/حذف: أدمن فقط
    execute format(
      'create policy "%s_write" on public.%s for all to authenticated
       using (public.has_role(auth.uid(), ''admin''))
       with check (public.has_role(auth.uid(), ''admin''))',
      tbl, tbl
    );

    -- الصلاحيات
    execute format('grant select on public.%I to anon, authenticated', tbl);
    execute format('grant all on public.%I to authenticated', tbl);
  end loop;
end $$;

