-- ========= 0. الاعتماديات المسبقة (تُتجاهل إن كانت موجودة) =========
do $$
begin
  if not exists (
    select 1 from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public' and t.typname = 'app_role'
  ) then
    execute 'create type public.app_role as enum (''admin'')';
  end if;
end $$;

create table if not exists public.user_roles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.app_role not null default 'admin',
  created_at timestamptz not null default now(),
  unique (user_id, role)
);

alter table public.user_roles enable row level security;

create or replace function public.has_role(_uid uuid, _role public.app_role)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.user_roles where user_id = _uid and role = _role)
$$;

grant execute on function public.has_role(uuid, public.app_role) to anon, authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'user_roles' and policyname = 'user_roles_select_self'
  ) then
    create policy "user_roles_select_self" on public.user_roles
      for select to authenticated
      using (user_id = auth.uid());
  end if;
  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'user_roles' and policyname = 'user_roles_admin_all'
  ) then
    create policy "user_roles_admin_all" on public.user_roles
      for all to authenticated
      using (public.has_role(auth.uid(), 'admin'))
      with check (public.has_role(auth.uid(), 'admin'));
  end if;
end $$;

grant select on public.user_roles to anon, authenticated;
grant all on public.user_roles to service_role;

