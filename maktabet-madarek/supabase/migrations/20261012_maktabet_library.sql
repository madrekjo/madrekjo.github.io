-- ========= 5. دخول أدمن المكتبة (رمز 3330116 مخزّن في القاعدة) =========
-- لا يستخدم login_admin_by_code الخاص بملفات المعلمين؛ رمز المكتبة
-- مستقل ويُغيّر من جدول maktabet_library_settings.
create or replace function public.maktabet_login_admin(p_code text)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
  _uid uuid := auth.uid();
  _pin text;
begin
  if _uid is null then
    return false;
  end if;
  select admin_pin into _pin from public.maktabet_library_settings where id = 1;
  if _pin is null or p_code <> _pin then
    return false;
  end if;
  insert into public.user_roles (user_id, role)
  values (_uid, 'admin'::public.app_role)
  on conflict (user_id, role) do nothing;
  return true;
end;
$$;

grant execute on function public.maktabet_login_admin(text) to anon, authenticated;

-- ========= 6. إدراج ملف جديد (تحقق مركزي بالحدود) =========
create or replace function public.maktabet_add_file(
  p_title text,
  p_description text,
  p_year smallint,
  p_subject text,
  p_term smallint,
  p_type text,
  p_ext text,
  p_size_bytes bigint,
  p_uploader text default 'مستخدم مجهول',
  p_storage_path text default null
)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  _limit bigint;
  _id uuid;
begin
  if nullif(trim(p_title), '') is null then
    raise exception 'title_required';
  end if;
  if p_year not in (2009, 2010) then
    raise exception 'invalid_year';
  end if;
  if p_term not in (1, 2) then
    raise exception 'invalid_term';
  end if;
  if lower(coalesce(p_ext, '')) not in ('pdf', 'jpg', 'jpeg', 'png') then
    raise exception 'invalid_ext';
  end if;
  select max_size_bytes into _limit from public.maktabet_library_settings where id = 1;
  _limit := coalesce(_limit, 10485760); -- 10MB افتراضياً
  if p_size_bytes is null or p_size_bytes <= 0 then
    raise exception 'invalid_size';
  end if;
  if p_size_bytes > _limit then
    raise exception 'size_limit_exceeded';
  end if;

  insert into public.maktabet_library_files
    (title, description, year, subject, term, type, ext, size_bytes, uploader, storage_path, status)
  values
    (trim(p_title),
     coalesce(nullif(trim(p_description), ''), ''),
     p_year, p_subject, p_term, p_type,
     lower(p_ext), p_size_bytes,
     coalesce(nullif(trim(p_uploader), ''), 'مستخدم مجهول'),
     p_storage_path, 'pending')
  returning id into _id;
  return _id;
end;
$$;

grant execute on function public.maktabet_add_file(
  text, text, smallint, text, smallint, text, text, bigint, text, text
) to anon, authenticated;

-- ========= 7. تحديث حالة ملف (إدارة) =========
create or replace function public.maktabet_set_status(
  p_file_id uuid,
  p_status text,
  p_note text default null
)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if public.has_role(auth.uid(), 'admin') is not true then
    return false;
  end if;
  if p_status not in ('pending', 'approved', 'rejected') then
    return false;
  end if;
  update public.maktabet_library_files
     set status = p_status,
         note = coalesce(p_note, note),
         updated_at = now()
   where id = p_file_id;
  return found;
end;
$$;

grant execute on function public.maktabet_set_status(uuid, text, text) to authenticated;

-- ========= 8. حذف ملف (إدارة) =========
create or replace function public.maktabet_delete_file(p_file_id uuid)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
  _path text;
begin
  if public.has_role(auth.uid(), 'admin') is not true then
    return false;
  end if;
  select storage_path into _path from public.maktabet_library_files where id = p_file_id;
  if _path is not null then
    delete from storage.objects
     where bucket_id = 'maktabet-library-files' and name = _path;
  end if;
  delete from public.maktabet_library_files where id = p_file_id;
  return found;
end;
$$;

grant execute on function public.maktabet_delete_file(uuid) to authenticated;

-- ========= 9. عدّاد التنزيلات (يزيد 1 فقط للملفات المعتمدة) =========
create or replace function public.maktabet_increment_download(p_file_id uuid)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  update public.maktabet_library_files
     set downloads = downloads + 1,
         updated_at = now()
   where id = p_file_id and status = 'approved';
  return found;
end;
$$;

grant execute on function public.maktabet_increment_download(uuid) to anon, authenticated;

