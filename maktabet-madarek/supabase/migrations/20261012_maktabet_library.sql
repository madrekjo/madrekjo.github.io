-- ========= 11. حارس حجم الملف (10MB) على مستوى التخزين =========
create or replace function public.maktabet_library_size_guard()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  _limit bigint;
begin
  if new.bucket_id = 'maktabet-library-files' then
    select max_size_bytes into _limit from public.maktabet_library_settings where id = 1;
    _limit := coalesce(_limit, 10485760); -- 10MB
    if coalesce((new.metadata ->> 'size')::bigint, 0) > _limit then
      raise exception 'size_limit_exceeded';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists maktabet_library_size_guard_trg on storage.objects;
create trigger maktabet_library_size_guard_trg
  before insert on storage.objects
  for each row execute function public.maktabet_library_size_guard();

