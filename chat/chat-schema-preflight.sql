-- ============================================================================
-- هدفه: إزالة ONLY ما قد يمنع تشغيل السكيما:
--   1) سياسات التخزين القديمة (السكربت ينشئها من جديد)
--   2) ترجّر إنشاء الملفات القديم (السكربت ينشئه من جديد)
--
-- ✔ لا يُحذف: لا صور، لا باكتات، لا مستخدمين، لا أي ملفات.
--    (الباكتات تبقى كما هي بصورها — السكربت المعدّل يتعامل معها بسلامة)
-- ----------------------------------------------------------------------------

-- 1) حذف كل سياسات التخزين القديمة فقط (تُعاد إنشاؤها بعد البناء)
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT policyname
    FROM pg_policies
    WHERE schemaname = 'storage' AND tablename = 'objects'
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON storage.objects', r.policyname);
  END LOOP;
END $$;

-- 2) إزالة ترجّر إنشاء الملف الشخصي القديم إن وُجد (السكربت ينشئه من جديد)
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

-- انتهى التنظيف — لا حذف لأي بيانات أو صور
SELECT 'تنظيف تم بنجاح — الصور محفوظة، جاهز لتشغيل database-schema-rebuild.sql' AS done;