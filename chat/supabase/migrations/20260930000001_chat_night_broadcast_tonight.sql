-- ============================================================================
-- بثّ وقت النوم في الدردشة: يفتح الحين ويغلق الساعة 3:00 فجراً بالضبط
-- ---------------------------------------------------------------------------
-- الوضع: البث موجود بالجدول لكن نافذته انتهت (منذ 00:00 UTC أمس)، فالنافذة
--        ما بتطلع لأحد. هذا الملف يفتحها الآن (= الآن) ويجعلها تنتهي تلقائياً
--        عند منتصف الليل UTC (= الساعة 3:00 بتوقيتنا UTC+3).
--
-- إعادة التشغيل: ينفع تنفّذه أي ليلة — يحدّث نفس الصف بدل ما يكرّره.
--   للمتابعة: بدّل نهاية النافذة فقط (ends_at) وخلّي العنوان والمحتوى.
-- ============================================================================

UPDATE public.broadcasts
   SET visible    = true,
       starts_at  = now() - INTERVAL '1 minute',
       -- الساعة 3:00 فجراً بتوقيتنا = 00:00 UTC
       expires_at = (((now() AT TIME ZONE 'UTC')::date + 1)::timestamp AT TIME ZONE 'UTC')
 WHERE kind = 'night';

