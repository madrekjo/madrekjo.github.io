-- الجولة تُحتسب ما دام التطبيق مفتوح — تغيّر التبويب أو التنقّل بالموقع
-- ما يقطع العدّاد.
-- ---------------------------------------------------------------------------
-- قبل: كل نبضة كانت تُدمج حتى 120 ثانية فقط، وأي غياب أكبر من 300 ثانية كان
--       يُعتبر "مستخدم غادر"، فيضيع وقت الجولة لمجرد تكبير التبويب أو
--       تصفّح صفحة أخرى داخل الموقع.
-- بعد: نافذة سماح 10 دقائق (600 ثانية) للدمج وللحيوية. المتصفح يخنق
--       المؤقتات في التبويبات المخفية إلى نحو نبضة في الدقيقة، فتبقى الفجوات
--       صغيرة، أما إغلاق المتصفح فيوقف الاحتساب بعد 10 دقائق كحد أقصى.
-- ============================================================================

-- أقصى ثوانٍ تُدمج في نبضة واحدة (نافذة الغياب المسموحة)
CREATE OR REPLACE FUNCTION public.round_beat_cap() RETURNS integer
  LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$ SELECT 600 $$;

-- بعد هذا الغياب تُعتبر مغادرة حقيقية (إغلاق المتصفح) ولا يُحتسب أي فاصل
CREATE OR REPLACE FUNCTION public.round_beat_liveness() RETURNS integer
  LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$ SELECT 600 $$;
